def compute(P, cost, k, a, L, R, b, S, O, ads, tax="usn6", rate=6, vat=0):
    """Та же формула, что в assets/calc.js — для примеров в тексте."""
    b = b / 100
    logi = L + (1 - b) / b * (L + R)
    fee = P * (k + a) / 100
    adv = P * ads / 100
    v = P * vat / (100 + vat) if vat else 0
    inc = P - v
    exp = cost + fee + logi + S + O + adv
    t = max((inc - exp) * rate / 100, inc * 0.01) if tax == "usn15" else inc * rate / 100
    return dict(logi=logi, fee=fee, ads=adv, vat=v, tax=t, profit=inc - exp - t, margin=(inc - exp - t) / P * 100)


